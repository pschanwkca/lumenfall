const KEYS = Object.keys(JA).sort((a, b) => b.length - a.length);
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const RX = new RegExp(KEYS.map(esc).join('|'), 'g');
const HAN = /[㐀-鿿]/;
export const I18N = { lang: 'zh' };
export function tr(s) { return I18N.lang === 'ja' && s && HAN.test(s) ? s.replace(RX, (m) => JA[m]) : s; }

const orig = new Map(); // text node -> [original, translated]
function doNode(n) {
  const d = n.data;
  if (!d || !HAN.test(d)) return;
  const rec = orig.get(n);
  if (rec && rec[1] === d) return;
  const out = d.replace(RX, (m) => JA[m]);
  if (out !== d) {
    orig.set(n, [d, out]); n.data = out;
    if (orig.size > 600) for (const k of orig.keys()) if (!k.isConnected) orig.delete(k);
  }
}
function walk(root) {
  if (root.nodeType === 3) { doNode(root); return; }
  if (root.nodeName === 'SCRIPT' || root.nodeName === 'STYLE') return;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let n; while ((n = w.nextNode())) doNode(n);
}
let obs = null;
export function setLang(lang) {
  I18N.lang = lang;
  document.documentElement.lang = lang === 'ja' ? 'ja' : 'zh-Hant';
  document.documentElement.classList.toggle('ja', lang === 'ja');
  if (lang === 'ja') {
    walk(document.body);
    if (!obs) {
      obs = new MutationObserver((ms) => {
        if (I18N.lang !== 'ja') return;
        for (const m of ms) {
          if (m.type === 'characterData') doNode(m.target);
          else for (const n of m.addedNodes) walk(n);
        }
      });
      obs.observe(document.body, { subtree: true, childList: true, characterData: true });
    }
  } else {
    for (const [n, [o, t]] of orig) if (n.data === t) n.data = o;
    orig.clear();
  }
}
